def atomic_number(symbol: str) -> int:
    try:
        number = ATOMIC_NUMBERS[str(symbol)]
    except KeyError as error:
        raise ValueError(f"Unknown element symbol {symbol!r}") from error
    if number == 0:
        raise ValueError("Dummy element X requires an explicit physical species")
    return number


def chemical_formula(numbers) -> str:
    """Hill-order formula, matching conventional structure import displays."""
    symbols, counts = np.unique([SYMBOLS[int(number)] for number in numbers], return_counts=True)
    mapping = dict(zip(symbols, counts))
    order = sorted(mapping)
    if "C" in mapping:
        order = ["C", *(["H"] if "H" in mapping else []), *[s for s in order if s not in {"C", "H"}]]
    return "".join(symbol + (str(mapping[symbol]) if mapping[symbol] != 1 else "") for symbol in order)
